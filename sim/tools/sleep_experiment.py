"""Sleep and memory (plan step 5.9, design E3): train, rest asleep or awake, then test.

    infra\\start-broker.cmd local                          (in another window)
    sim\\.venv\\Scripts\\python sim\\tools\\sleep_experiment.py --animals 10
    sim\\.venv\\Scripts\\python sim\\tools\\sleep_experiment.py --report-only

Scenario scenarios/sleep_learning.yaml: training as in step 5.6 (punish the lit source, starts near
it), then 10 min of robot time without odour, then a post-test of 8 trials. The rest is dark (the
brain falls asleep after 20 s of darkness; consolidation moves labile depression into the stable
part) or lit (awake: labile depression is forgotten). Both end with 10 s of light (dawn). Forgetting
is on (neural.forget_tau_s 300); consolidation tau 60 s. Hunger is held at 0 (no rise), so the
post-test measures memory, not hunger. These time constants were fixed in advance,
and the outcome largely follows from them: this demonstrates the mechanism in the closed loop, it is
not a discovery.

Each animal is a fresh brain (--no-persistence, seed k + 1, no reset on reboot), runs both
conditions in turn with the same seeds (paired), and odd animals get the mirrored arena.
Results: .local/experiments/sleep/ (records.csv per animal x condition x phase, report.md).
"""
from __future__ import annotations

import argparse
import copy
import csv
import logging
import statistics
import sys
import time
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from flybot_contract import Contract  # noqa: E402
from flybot_sim.__main__ import open_link  # noqa: E402
from flybot_sim.batch import run_experiment  # noqa: E402
from flybot_sim.config import REPO, load_scenario, mirror_scenario  # noqa: E402
from flybot_sim.learning import sign_test, summarize_phase, weight_means  # noqa: E402
from learning_experiment import Monitor, start_brain, stop_brain  # noqa: E402

log = logging.getLogger("sleep")
CONDITIONS = {"sleep": 0.0, "awake": 0.8}         # light level during the rest phase
FORGET_TAU_S = 300.0
CONSOLIDATE_TAU_S = 60.0
COLUMNS = ["condition", "animal", "mirrored", "phase", "n", "lit", "dark", "timeout", "pi", "pref_lt", "pref_odr",
           "w_ap", "w_av", "slept", "lockstep_timeouts"]


class SleepMonitor(Monitor):
    """Also notes whether the brain reported sleep (brain/state slp) since the last reset."""

    def __init__(self, contract):
        super().__init__(contract)
        self.slept = False

    def _on_message(self, client, userdata, m):
        super()._on_message(client, userdata, m)
        with self.lock:
            if self.state and self.state.get("slp"):
                self.slept = True

    def take_slept(self) -> bool:
        with self.lock:
            s, self.slept = self.slept, False
            return s


def brain_config(out: Path) -> Path:
    cfg = yaml.safe_load((REPO / "brain" / "config" / "brain.yaml").read_text(encoding="utf-8"))
    cfg.setdefault("timing", {})["weights_every_ms"] = 2000     # with forgetting the weights change every tick:
                                                                 # 250 ms made each publish a bottleneck (B)
    cfg.setdefault("neural", {})["forget_tau_s"] = FORGET_TAU_S
    sl = cfg.setdefault("sleep", {})
    sl["auto"] = True
    sl["consolidate_tau_s"] = CONSOLIDATE_TAU_S
    st = cfg.setdefault("states", {})                # hunger held at 0 (approved): after the 10 min rest it
    st["hunger_start"], st["hunger_rise_s"] = 0.0, 0  # would otherwise be ~1 and mask the memory in both groups
    p = out / "brain-sleep-experiment.yaml"
    p.write_text("# generated by sim/tools/sleep_experiment.py from brain/config/brain.yaml\n"
                 + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    return p


def run_animal(base, condition: str, k: int, out: Path, monitor: SleepMonitor, config: Path) -> list[dict]:
    sc = copy.deepcopy(base)
    sc.seed = base.seed + 1000 * k
    mirrored = k % 2 == 1
    if mirrored:
        sc = mirror_scenario(sc)
    for ph in sc.experiment.phases:
        if ph.kind == "rest":
            ph.ambient = CONDITIONS[condition]
    sc.name = f"{base.name}-{condition}-a{k:02d}"
    folder = out / condition
    folder.mkdir(parents=True, exist_ok=True)
    monitor.reset()
    monitor.take_slept()
    brain = start_brain(k + 1, folder / f"brain-a{k:02d}.log", monitor, str(config))
    records = []

    def on_phase_end(phase: str, rows: list[dict]) -> None:
        time.sleep(0.3)
        pref, weights = monitor.snapshot()
        w_ap, w_av = weight_means(weights)
        s = summarize_phase(rows)
        records.append({"condition": condition, "animal": k, "mirrored": mirrored, "phase": phase, "n": s.n,
                        "lit": s.lit, "dark": s.dark, "timeout": s.timeout,
                        "pi": None if s.pi is None else round(s.pi, 3), "pref_lt": pref.get("lt"),
                        "pref_odr": pref.get("odr"), "w_ap": w_ap, "w_av": w_av, "slept": monitor.take_slept(),
                        "lockstep_timeouts": sum(int(r["lockstep_timeouts"] or 0) for r in rows)})
        log.info("  %s %-5s lit %d dark %d timeout %d  pref.lt %s  w ap %s  slept %s", condition, phase, s.lit,
                 s.dark, s.timeout, pref.get("lt"), w_ap, records[-1]["slept"])

    try:
        run_experiment(sc, "neural", folder / f"trials-a{k:02d}.csv", open_link, on_phase_end,
                       catch_up=monitor.wait_caught_up)
    finally:
        stop_brain(brain)
    return records


def _num(x):
    return None if x in ("", None) else float(x)


def report(records: list[dict]) -> str:
    by = {(r["condition"], int(r["animal"]), r["phase"]): r for r in records}
    animals = sorted({int(r["animal"]) for r in records})
    phases = list(dict.fromkeys(r["phase"] for r in records))
    out = ["# Sleep and memory (step 5.9, design E3)", "",
           f"{len(animals)} animals. Forgetting tau {FORGET_TAU_S:g} s, consolidation tau {CONSOLIDATE_TAU_S:g} s "
           "(fixed in advance; a demonstration of the mechanism).", "",
           "| condition | phase | lit / dark / timeout per animal | PI | pref.lt | w KC→ap | brain slept |",
           "|---|---|---|---|---|---|---|"]
    for c in CONDITIONS:
        for ph in phases:
            rs = [by[(c, a, ph)] for a in animals if (c, a, ph) in by]
            if not rs:
                continue
            m = lambda key: statistics.fmean(int(r[key]) for r in rs)  # noqa: E731
            vals = lambda key: [v for v in (_num(r[key]) for r in rs) if v is not None]  # noqa: E731
            f = lambda xs, fmt="{:+.2f}": fmt.format(statistics.fmean(xs)) if xs else "–"  # noqa: E731
            out.append(f"| {c} | {ph} | {m('lit'):.1f} / {m('dark'):.1f} / {m('timeout'):.1f} | {f(vals('pi'))} | "
                       f"{f(vals('pref_lt'))} | {f(vals('w_ap'), '{:.3f}')} | "
                       f"{sum(str(r['slept']) == 'True' for r in rs)}/{len(rs)} |")
    out += ["", "Paired per animal, sleep minus awake (up / down / tie, exact sign test):", "",
            "| measure | mean | up / down / tie | p |", "|---|---|---|---|"]

    def paired(name, phase, f):
        d = []
        for a in animals:
            s, w = by.get(("sleep", a, phase)), by.get(("awake", a, phase))
            if s and w and f(s) is not None and f(w) is not None:
                d.append(f(s) - f(w))
        if d:
            up, down = sum(x > 0 for x in d), sum(x < 0 for x in d)
            out.append(f"| {name} | {statistics.fmean(d):+.3f} | {up} / {down} / {len(d) - up - down} | "
                       f"{sign_test(up, down):.3f} |")

    paired("w KC→ap after the rest (lower = more retained)", "rest", lambda r: _num(r["w_ap"]))
    paired("post-test PI (lower = more avoidance retained)", "post", lambda r: _num(r["pi"]))
    paired("post-test lit approaches", "post", lambda r: int(r["lit"]))
    paired("post-test pref.lt", "post", lambda r: _num(r["pref_lt"]))
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--animals", type=int, default=10)
    ap.add_argument("--first-animal", type=int, default=0)
    ap.add_argument("--scenario", default="sleep_learning")
    ap.add_argument("--out", default=str(REPO / ".local" / "experiments" / "sleep"))
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", datefmt="%H:%M:%S")
    logging.getLogger("flybot_sim").setLevel(logging.WARNING)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rec_path = out / "records.csv"
    records = list(csv.DictReader(rec_path.open(encoding="utf-8"))) if rec_path.exists() else []
    if not args.report_only:
        base = load_scenario(args.scenario)
        config = brain_config(out)
        done = {(r["condition"], int(r["animal"])) for r in records}
        monitor = SleepMonitor(Contract())
        monitor.start()
        new = not rec_path.exists()
        try:
            with rec_path.open("a", newline="", encoding="utf-8") as f:
                w = csv.DictWriter(f, fieldnames=COLUMNS)
                if new:
                    w.writeheader()
                for k in range(args.first_animal, args.first_animal + args.animals):
                    for condition in CONDITIONS:                 # interleaved
                        if (condition, k) in done:
                            continue
                        t0 = time.perf_counter()
                        rows = run_animal(base, condition, k, out, monitor, config)
                        for r in rows:
                            w.writerow({c: ("" if r[c] is None else r[c]) for c in COLUMNS})
                        f.flush()
                        records += [{c: ("" if r[c] is None else str(r[c])) for c in COLUMNS} for r in rows]
                        log.info("%s animal %d done in %.0f s", condition, k, time.perf_counter() - t0)
        finally:
            monitor.stop()
    text = report(records)
    (out / "report.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
