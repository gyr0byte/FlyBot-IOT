"""Hunger vs fear experiment (plan step 5.7, design E1).

    infra\\start-broker.cmd local                          (in another window)
    sim\\.venv\\Scripts\\python sim\\tools\\state_experiment.py --animals 10
    sim\\.venv\\Scripts\\python sim\\tools\\state_experiment.py --report-only

2 x 2 design on scenarios/threat.yaml (one source guarded by a recurring looming threat):
fed (hunger starts at 0) vs hungry (starts at 1), with the threat vs without it. Each animal k is a
brain seed (k + 1); in each cell it runs `trials` independent trials (--reset-on-reboot: hunger
restarts at its condition's value every trial, per-trial brain seeds). Animal k has the same trial
seeds and starts in every cell (paired), and its four cells run back to back (interleaved).
Habituation must be off (edge override hab_enabled: false) so repeated threats cannot habituate and
confound hunger vs fear; the tool refuses to run otherwise.

Results go to .local/experiments/states/ (git-ignored): trial CSVs, brain logs, records.csv (one row
per animal and cell, resumable) and report.md.
"""
from __future__ import annotations

import argparse
import copy
import csv
import logging
import statistics
import sys
import time
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from flybot_contract import Contract  # noqa: E402
from flybot_sim.__main__ import open_link  # noqa: E402
from flybot_sim.batch import run_trials  # noqa: E402
from flybot_sim.config import REPO, load_scenario  # noqa: E402
from flybot_sim.learning import sign_test  # noqa: E402
from learning_experiment import Monitor, start_brain, stop_brain  # noqa: E402

log = logging.getLogger("states")
CELLS = [("fed", 0.0, True), ("hungry", 1.0, True), ("fed", 0.0, False), ("hungry", 1.0, False)]
COLUMNS = ["animal", "hunger", "threat", "n", "reached", "timeouts", "median_time_s", "escapes", "threats",
           "min_dist_m", "lockstep_timeouts"]


def cell_name(h: str, threat: bool) -> str:
    return f"{h}-{'threat' if threat else 'nothreat'}"


def brain_config(out: Path, hunger_start: float) -> Path:
    cfg = yaml.safe_load((REPO / "brain" / "config" / "brain.yaml").read_text(encoding="utf-8"))
    cfg.setdefault("states", {})["hunger_start"] = hunger_start
    p = out / f"brain-hunger{hunger_start:g}.yaml"
    p.write_text("# generated by sim/tools/state_experiment.py from brain/config/brain.yaml\n"
                 + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    return p


def run_cell(base, k: int, hunger: str, h0: float, threat: bool, trials: int, out: Path, monitor) -> dict:
    sc = copy.deepcopy(base)
    sc.seed = base.seed + 1000 * k                   # same trials for animal k in every cell
    if not threat:
        sc.threats = []
    sc.name = f"{base.name}-{cell_name(hunger, threat)}-a{k:02d}"
    folder = out / cell_name(hunger, threat)
    folder.mkdir(parents=True, exist_ok=True)
    brain = start_brain(k + 1, folder / f"brain-a{k:02d}.log", monitor, str(brain_config(out, h0)),
                        extra=["--reset-on-reboot"])
    try:
        rows = run_trials(sc, trials, "neural", False, folder / f"trials-a{k:02d}.csv", open_link)
    finally:
        stop_brain(brain)
    reached = [r for r in rows if r["reached"] == "yes"]
    mean = lambda key: round(statistics.fmean(float(r[key] or 0) for r in rows), 3)  # noqa: E731
    return {"animal": k, "hunger": hunger, "threat": threat, "n": len(rows), "reached": len(reached),
            "timeouts": len(rows) - len(reached),
            "median_time_s": round(statistics.median(float(r["time_to_source_s"]) for r in reached), 2) if reached else "",
            "escapes": mean("escapes"), "threats": mean("threats"), "min_dist_m": mean("min_source_dist_m"),
            "lockstep_timeouts": sum(int(r["lockstep_timeouts"] or 0) for r in rows)}


def report(records: list[dict]) -> str:
    def get(k, h, threat):
        return next((r for r in records if int(r["animal"]) == k and r["hunger"] == h
                     and str(r["threat"]) == str(threat)), None)
    animals = sorted({int(r["animal"]) for r in records})
    out = ["# Hunger vs fear (step 5.7, design E1)", "",
           f"{len(animals)} animals, habituation off. Per cell: means over animals.", "",
           "| cell | reached | median time to source | escapes / trial | threats / trial | closest approach |",
           "|---|---|---|---|---|---|"]
    for h, _, threat in CELLS:
        rs = [r for r in (get(k, h, threat) for k in animals) if r]
        if not rs:
            continue
        n = sum(int(r["n"]) for r in rs)
        times = [float(r["median_time_s"]) for r in rs if r["median_time_s"] not in ("", None)]
        out.append(f"| {cell_name(h, threat)} | {sum(int(r['reached']) for r in rs) / n:.0%} | "
                   f"{statistics.median(times):.1f} s | {statistics.fmean(float(r['escapes']) for r in rs):.2f} | "
                   f"{statistics.fmean(float(r['threats']) for r in rs):.2f} | "
                   f"{statistics.fmean(float(r['min_dist_m']) for r in rs):.2f} m |")
    out += ["", "Paired per animal (difference in reached trials; up / down / tie; exact two-sided sign test):", "",
            "| comparison | mean difference | up / down / tie | p |", "|---|---|---|---|"]

    def reach(k, h, threat):
        r = get(k, h, threat)
        return None if r is None else int(r["reached"])

    def contrast(k, terms):
        """terms: [(sign, hunger, threat)]; None if any cell is missing for animal k."""
        vals = [reach(k, h, threat) for _, h, threat in terms]
        return None if None in vals else sum(s * v for (s, _, _), v in zip(terms, vals))

    comparisons = [
        ("hungry - fed, with threat", [(1, "hungry", True), (-1, "fed", True)]),
        ("hungry - fed, without threat", [(1, "hungry", False), (-1, "fed", False)]),
        ("threat - none, fed", [(1, "fed", True), (-1, "fed", False)]),
        ("threat - none, hungry", [(1, "hungry", True), (-1, "hungry", False)]),
        ("interaction: (hungry - fed) with threat minus without",
         [(1, "hungry", True), (-1, "fed", True), (-1, "hungry", False), (1, "fed", False)]),
    ]
    for name, terms in comparisons:
        d = [x for x in (contrast(k, terms) for k in animals) if x is not None]
        if not d:
            continue
        up, down = sum(x > 0 for x in d), sum(x < 0 for x in d)
        out.append(f"| {name} | {statistics.fmean(d):+.2f} | {up} / {down} / {len(d) - up - down} | "
                   f"{sign_test(up, down):.3f} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--animals", type=int, default=10)
    ap.add_argument("--first-animal", type=int, default=0)
    ap.add_argument("--trials", type=int, default=10, help="independent trials per animal and cell")
    ap.add_argument("--scenario", default="threat")
    ap.add_argument("--out", default=str(REPO / ".local" / "experiments" / "states"))
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", datefmt="%H:%M:%S")
    logging.getLogger("flybot_sim").setLevel(logging.WARNING)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rec_path = out / "records.csv"
    records = list(csv.DictReader(rec_path.open(encoding="utf-8"))) if rec_path.exists() else []
    if not args.report_only:
        base = load_scenario(args.scenario)
        if base.edge.get("hab_enabled", True) is not False:
            raise SystemExit(f"scenario {base.name!r} must disable habituation (edge: hab_enabled: false)")
        if not base.threats:
            raise SystemExit(f"scenario {base.name!r} has no threats")
        done = {(int(r["animal"]), r["hunger"], str(r["threat"])) for r in records}
        monitor = Monitor(Contract())
        monitor.start()
        new = not rec_path.exists()
        try:
            with rec_path.open("a", newline="", encoding="utf-8") as f:
                w = csv.DictWriter(f, fieldnames=COLUMNS)
                if new:
                    w.writeheader()
                for k in range(args.first_animal, args.first_animal + args.animals):
                    for h, h0, threat in CELLS:              # interleaved: animal k runs all four cells
                        if (k, h, str(threat)) in done:
                            continue
                        t0 = time.perf_counter()
                        rec = run_cell(base, k, h, h0, threat, args.trials, out, monitor)
                        w.writerow({c: ("" if rec[c] is None else rec[c]) for c in COLUMNS})
                        f.flush()
                        records.append({c: str(rec[c]) for c in COLUMNS})
                        log.info("animal %d %s: reached %d/%d, escapes %.2f, threats %.2f (%.0f s)", k,
                                 cell_name(h, threat), rec["reached"], rec["n"], rec["escapes"], rec["threats"],
                                 time.perf_counter() - t0)
        finally:
            monitor.stop()
    text = report(records)
    (out / "report.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
