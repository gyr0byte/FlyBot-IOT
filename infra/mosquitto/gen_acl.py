"""Generate the Mosquitto ACL file from the permission table in docs/message-contract.md.

The contract is the source of truth (section 4, table "P = may publish, S = may subscribe").
Rules:
  - P and S -> "topic readwrite", P only -> "topic write", S only -> "topic read".
  - A user that may subscribe to EVERY topic in the table gets one "topic read flybot/01/#"
    line instead of a read line per topic (this is how the contract gives brain/logger
    access to every topic), plus a "topic write" line for each topic it may publish.

Usage (from the repo root):
  infra\\.venv\\Scripts\\python infra\\mosquitto\\gen_acl.py           write infra/mosquitto/acl
  infra\\.venv\\Scripts\\python infra\\mosquitto\\gen_acl.py --check   exit 1 if the file is out of date

Standard library only.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONTRACT = REPO / "docs" / "message-contract.md"
ACL_FILE = REPO / "infra" / "mosquitto" / "acl"
USERS = ["esp32", "sim", "brain", "dashboard", "bot"]
PREFIX = "flybot/01/"


def contract_revision(text: str) -> str:
    m = re.search(r"\*\*Contract revision:\*\* (\d+)", text)
    if not m:
        raise SystemExit("contract revision not found in docs/message-contract.md")
    return m.group(1)


def parse_table(text: str | None = None) -> tuple[list[str], dict[tuple[str, str], tuple[bool, bool]]]:
    """Return (topics in table order, {(user, topic): (may_publish, may_subscribe)})."""
    if text is None:
        text = CONTRACT.read_text(encoding="utf-8")
    try:
        sec4 = text.split("## 4. MQTT users")[1].split("### 4.1")[0]
    except IndexError:
        raise SystemExit("section 4 not found in docs/message-contract.md")
    header = re.search(r"^\| Topic \| (.+) \|$", sec4, flags=re.M)
    if not header or [h.strip() for h in header.group(1).split("|")] != USERS:
        raise SystemExit(f"section 4 table header must list users {USERS}")
    topics: list[str] = []
    perms: dict[tuple[str, str], tuple[bool, bool]] = {}
    row_re = r"^\| `([a-z0-9/]+)` \|" + r" ([^|]*) \|" * len(USERS) + r"$"
    for m in re.finditer(row_re, sec4, flags=re.M):
        topic = m.group(1)
        topics.append(topic)
        for user, cell in zip(USERS, m.groups()[1:]):
            cell = cell.strip()
            if cell not in ("P", "S", "P S", "–", "-"):
                raise SystemExit(f"unexpected cell {cell!r} for {user} / {topic}")
            perms[(user, topic)] = ("P" in cell, "S" in cell)
    if not topics:
        raise SystemExit("no topic rows found in the section 4 table")
    return topics, perms


def render(text: str | None = None) -> str:
    if text is None:
        text = CONTRACT.read_text(encoding="utf-8")
    topics, perms = parse_table(text)
    out = [
        "# FlyBot Mosquitto ACL. GENERATED by infra/mosquitto/gen_acl.py from the permission",
        f"# table in docs/message-contract.md section 4 (contract revision {contract_revision(text)}).",
        "# Do not edit by hand: change the contract, then re-run gen_acl.py.",
        "# Anonymous clients are refused by the broker config (allow_anonymous false).",
    ]
    for user in USERS:
        out += ["", f"user {user}"]
        reads_all = all(perms[(user, t)][1] for t in topics)
        if reads_all:
            out.append(f"topic read {PREFIX}#")
        for t in topics:
            pub, sub = perms[(user, t)]
            if reads_all:
                if pub:
                    out.append(f"topic write {PREFIX}{t}")
            elif pub and sub:
                out.append(f"topic readwrite {PREFIX}{t}")
            elif pub:
                out.append(f"topic write {PREFIX}{t}")
            elif sub:
                out.append(f"topic read {PREFIX}{t}")
    return "\n".join(out) + "\n"


def main() -> int:
    acl = render()
    if "--check" in sys.argv:
        current = ACL_FILE.read_text(encoding="utf-8") if ACL_FILE.exists() else ""
        if current != acl:
            print("infra/mosquitto/acl is OUT OF DATE with docs/message-contract.md; run gen_acl.py")
            return 1
        print("infra/mosquitto/acl is up to date")
        return 0
    ACL_FILE.write_text(acl, encoding="utf-8", newline="\n")
    print(f"wrote {ACL_FILE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
